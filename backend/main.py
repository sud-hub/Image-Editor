@app.post("/api/compress")
async def compress_image(
    file: UploadFile = File(...),
    quality: int = Form(85)
):
    """Compress image with specified quality (1-100)"""
    try:
        print(f"Compress request: quality={quality}")
        image_data = await file.read()
        image = Image.open(io.BytesIO(image_data))
        
        # Clamp quality between 1 and 100
        quality = max(1, min(100, quality))
        
        output_id = str(uuid.uuid4())
        output_path = TEMP_DIR / f"{output_id}.jpg"
        
        # Convert RGBA to RGB for JPEG compression
        if image.mode in ('RGBA', 'LA', 'P'):
            background = Image.new('RGB', image.size, (255, 255, 255))
            if image.mode == 'P':
                image = image.convert('RGBA')
            background.paste(image, mask=image.split()[-1] if image.mode == 'RGBA' else None)
            image = background
        
        # Save with specified quality
        image.save(output_path, "JPEG", quality=quality, optimize=True)
        
        # Get file size
        file_size = output_path.stat().st_size
        file_size_kb = file_size / 1024
        
        print(f"Compressed to {file_size_kb:.2f} KB at quality {quality}")
        
        return FileResponse(
            output_path, 
            media_type="image/jpeg",
            headers={
                "X-File-Size": str(file_size),
                "X-File-Size-KB": f"{file_size_kb:.2f}"
            }
        )
    except Exception as e:
        print(f"Compress error: {type(e).__name__}: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))

@app.post("/api/convert")
async def convert_format(
    file: UploadFile = File(...),
    format: str = Form("png")
):
    """Convert image format"""
    try:
        image_data = await file.read()
        image = Image.open(io.BytesIO(image_data))
        
        output_id = str(uuid.uuid4())
        
        if format == "png":
            output_path = TEMP_DIR / f"{output_id}.png"
            image.save(output_path, "PNG", optimize=True)
            media_type = "image/png"
        elif format in ["jpg", "jpeg"]:
            if image.mode in ('RGBA', 'LA', 'P'):
                # Convert to RGB for JPEG (no transparency support)
                background = Image.new('RGB', image.size, (255, 255, 255))
                if image.mode == 'P':
                    image = image.convert('RGBA')
                background.paste(image, mask=image.split()[-1] if image.mode == 'RGBA' else None)
                image = background
            output_path = TEMP_DIR / f"{output_id}.jpg"
            image.save(output_path, "JPEG", quality=95, optimize=True)
            media_type = "image/jpeg"
        elif format == "webp":
            output_path = TEMP_DIR / f"{output_id}.webp"
            image.save(output_path, "WEBP", quality=90)
            media_type = "image/webp"
        elif format == "bmp":
            if image.mode == 'RGBA':
                image = image.convert('RGB')
            output_path = TEMP_DIR / f"{output_id}.bmp"
            image.save(output_path, "BMP")
            media_type = "image/bmp"
        elif format == "tiff":
            output_path = TEMP_DIR / f"{output_id}.tiff"
            image.save(output_path, "TIFF", compression="tiff_deflate")
            media_type = "image/tiff"
        elif format == "gif":
            if image.mode == 'RGBA':
                image = image.convert('RGB')
            output_path = TEMP_DIR / f"{output_id}.gif"
            image.save(output_path, "GIF", optimize=True)
            media_type = "image/gif"
        elif format == "ico":
            if image.mode == 'RGBA':
                image = image.convert('RGB')
            output_path = TEMP_DIR / f"{output_id}.ico"
            # ICO format typically uses smaller sizes
            image.thumbnail((256, 256), Image.Resampling.LANCZOS)
            image.save(output_path, "ICO")
            media_type = "image/x-icon"
        else:
            raise HTTPException(status_code=400, detail=f"Unsupported format: {format}")
        
        print(f"Converted to {format.upper()}: saved to {output_path}")
        return FileResponse(output_path, media_type=media_type)
    except Exception as e:
        print(f"Convert error: {type(e).__name__}: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))

