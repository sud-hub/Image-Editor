@app.post("/api/crop")
async def crop_image(
    file: UploadFile = File(...),
    x: int = Form(0),
    y: int = Form(0),
    width: int = Form(100),
    height: int = Form(100)
):
    """Crop image to specified dimensions
    
    Coordinates are in image space (actual pixel coordinates).
    PIL's crop() method uses box=(left, upper, right, lower) format.
    Reference: https://pillow.readthedocs.io/en/stable/reference/Image.html#PIL.Image.Image.crop
    """
    try:
        image_data = await file.read()
        image = Image.open(io.BytesIO(image_data))
        
        # Get image dimensions
        img_width, img_height = image.size
        
        print(f"Crop request: x={x}, y={y}, width={width}, height={height}")
        print(f"Image dimensions: {img_width}x{img_height}")
        
        # Clamp coordinates to image bounds
        x = max(0, min(x, img_width - 1))
        y = max(0, min(y, img_height - 1))
        
        # Calculate bottom-right corner
        x2 = min(x + width, img_width)
        y2 = min(y + height, img_height)
        
        # Ensure we have a valid crop area (at least 1x1 pixel)
        if x2 <= x or y2 <= y:
            raise ValueError(f"Invalid crop area: box=({x}, {y}, {x2}, {y2})")
        
        print(f"Cropping with box: ({x}, {y}, {x2}, {y2})")
        print(f"Crop dimensions: {x2-x}x{y2-y}")
        
        # PIL crop uses (left, upper, right, lower) format
        cropped = image.crop((x, y, x2, y2))
        
        output_id = str(uuid.uuid4())
        output_path = TEMP_DIR / f"{output_id}.png"
        cropped.save(output_path, "PNG")
        
        print(f"Crop successful: saved to {output_path}")
        
        return FileResponse(output_path, media_type="image/png")
    except Exception as e:
        print(f"Crop error: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))

