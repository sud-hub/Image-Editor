@app.post("/api/filter")
async def apply_filter(
    file: UploadFile = File(...),
    filter_type: str = Form(...)
):
    """Apply filters using OpenCV"""
    try:
        print(f"Filter request: filter_type={filter_type}, file={file.filename}")
        image_data = await file.read()
        print(f"Image data size: {len(image_data)} bytes")
        nparr = np.frombuffer(image_data, np.uint8)
        img = cv2.imdecode(nparr, cv2.IMREAD_COLOR)
        
        if img is None:
            raise ValueError("Failed to decode image")
        
        if filter_type == "blur":
            img = cv2.GaussianBlur(img, (15, 15), 0)
        elif filter_type == "sharpen":
            kernel = np.array([[-1,-1,-1], [-1,9,-1], [-1,-1,-1]])
            img = cv2.filter2D(img, -1, kernel)
        elif filter_type == "edge":
            img = cv2.Canny(img, 100, 200)
            img = cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
        elif filter_type == "emboss":
            kernel = np.array([[-2,-1,0], [-1,1,1], [0,1,2]])
            img = cv2.filter2D(img, -1, kernel)
        elif filter_type == "sepia":
            kernel = np.array([[0.272, 0.534, 0.131],
                             [0.349, 0.686, 0.168],
                             [0.393, 0.769, 0.189]])
            img = cv2.transform(img, kernel)
        elif filter_type == "vintage":
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
            img = np.array(img, dtype=np.float64)
            img[:,:,0] = img[:,:,0] * 0.9
            img[:,:,2] = img[:,:,2] * 1.1
            img = np.clip(img, 0, 255).astype(np.uint8)
            img = cv2.cvtColor(img, cv2.COLOR_RGB2BGR)
        elif filter_type == "grayscale":
            img = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
            img = cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
        else:
            raise ValueError(f"Invalid filter type: {filter_type}")
        
        output_id = str(uuid.uuid4())
        output_path = TEMP_DIR / f"{output_id}.png"
        success = cv2.imwrite(str(output_path), img)
        
        if not success:
            raise ValueError("Failed to write image")
        
        print(f"Filter successful: saved to {output_path}")
        return FileResponse(output_path, media_type="image/png")
    except Exception as e:
        print(f"Filter error: {type(e).__name__}: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=str(e))

